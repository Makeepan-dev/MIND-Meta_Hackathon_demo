"""
MIND Universal Development Studio — AI-Driven Website Design Architecture.
Eliminates hardcoded domain dictionaries and templates.
Coordinates with the connected AI provider to dynamically determine:
- Purpose, audience, and information architecture
- Visual direction, typography, and responsive color palettes
- Component hierarchy, section layouts, and interactive form definitions
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from typing import Dict, Any, List, Optional


@dataclass
class AIDesignPlan:
    """Structured architectural plan generated by the AI provider for a web project."""
    title: str
    purpose: str
    target_audience: str
    visual_direction: str
    color_palette: Dict[str, str]
    typography: Dict[str, str]
    hero: Dict[str, str]
    sections: List[Dict[str, Any]]
    form_spec: Optional[Dict[str, Any]]
    pages: List[Dict[str, str]]
    features: List[str]
    ai_provider: str = "unknown"
    is_fallback: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return {
            "title": self.title,
            "purpose": self.purpose,
            "target_audience": self.target_audience,
            "visual_direction": self.visual_direction,
            "color_palette": self.color_palette,
            "typography": self.typography,
            "hero": self.hero,
            "sections": self.sections,
            "form_spec": self.form_spec,
            "pages": self.pages,
            "features": self.features,
            "ai_provider": self.ai_provider,
            "is_fallback": self.is_fallback,
        }


class AIDesignPlanner:
    """Generates website design plans dynamically using the connected AI model."""

    @classmethod
    def plan(
        cls,
        title: str,
        description: str,
        theme: Optional[str] = None,
        coding_adapter: Optional[Any] = None,
        requested_pages: Optional[List[str]] = None,
    ) -> AIDesignPlan:
        """
        Invokes the AI model to reason about requirements, domain, and design system.
        If the AI provider is offline or unavailable, generates a neutral, dynamic fallback
        plan without any hardcoded domain dictionaries or canned recipes.
        """
        # If an AI adapter is provided and not in offline test mode, query the brain
        if coding_adapter is not None:
            is_test_mode = getattr(getattr(coding_adapter, "config", None), "test_mode", False)
            if not is_test_mode:
                plan = cls._query_ai_brain_for_plan(
                    title=title,
                    description=description,
                    theme=theme,
                    coding_adapter=coding_adapter,
                    requested_pages=requested_pages or ["index.html"],
                )
                if plan is not None:
                    return plan

        # Otherwise, synthesize a clean, neutral, dynamic fallback plan
        return cls._create_dynamic_neutral_plan(
            title=title,
            description=description,
            theme=theme,
            requested_pages=requested_pages or ["index.html"],
        )

    @classmethod
    def _query_ai_brain_for_plan(
        cls,
        title: str,
        description: str,
        theme: Optional[str],
        coding_adapter: Any,
        requested_pages: List[str],
    ) -> Optional[AIDesignPlan]:
        """Queries the connected AI provider for a structured design specification."""
        prompt = (
            f"You are a master digital product architect and design director.\n"
            f"Analyze the following user request and create a tailored website design plan.\n"
            f"User Title: '{title}'\n"
            f"User Requirements: '{description}'\n"
            f"Requested Style/Theme: '{theme or 'modern, high-contrast, professional'}'\n"
            f"Requested Pages: {requested_pages}\n\n"
            f"Create a cohesive design plan tailored specifically to these requirements.\n"
            f"Return ONLY valid JSON matching this schema:\n"
            f"{{\n"
            f'  "title": "{title}",\n'
            f'  "purpose": "Target purpose of this site",\n'
            f'  "target_audience": "Who this site serves",\n'
            f'  "visual_direction": "Aesthetic style and mood",\n'
            f'  "color_palette": {{\n'
            f'    "primary": "#hex",\n'
            f'    "primary_hover": "#hex",\n'
            f'    "secondary": "#hex",\n'
            f'    "accent": "#hex",\n'
            f'    "bg_dark": "#hex",\n'
            f'    "bg_card_dark": "#hex",\n'
            f'    "text_dark": "#hex",\n'
            f'    "bg_light": "#hex",\n'
            f'    "bg_card_light": "#hex",\n'
            f'    "text_light": "#hex"\n'
            f'  }},\n'
            f'  "typography": {{\n'
            f'    "display": "font family or CSS stack",\n'
            f'    "body": "font family or CSS stack"\n'
            f'  }},\n'
            f'  "hero": {{\n'
            f'    "badge": "Short badge tag",\n'
            f'    "heading": "Compelling main display heading",\n'
            f'    "subtitle": "Informative subtitle",\n'
            f'    "cta_primary": "Primary action button label",\n'
            f'    "cta_target": "Link target (e.g. #action or contact.html)",\n'
            f'    "cta_secondary": "Secondary action label",\n'
            f'    "cta_secondary_target": "Link target"\n'
            f'  }},\n'
            f'  "sections": [\n'
            f'    {{\n'
            f'      "id": "features",\n'
            f'      "type": "cards",\n'
            f'      "heading": "Section heading",\n'
            f'      "lead": "Section lead text",\n'
            f'      "cards": [\n'
            f'        {{"title": "...", "description": "...", "badge": "..."}}\n'
            f'      ]\n'
            f'    }}\n'
            f'  ],\n'
            f'  "form_spec": {{\n'
            f'    "id": "main-action-form",\n'
            f'    "heading": "Action form heading",\n'
            f'    "lead": "Form instructions",\n'
            f'    "submit_label": "Submit button text",\n'
            f'    "fields": [\n'
            f'      {{"name": "...", "label": "...", "type": "text|email|date|select|textarea", "required": true/false, "options": []}}\n'
            f'    ]\n'
            f'  }},\n'
            f'  "pages": [\n'
            f'    {{"filename": "index.html", "title": "Home", "purpose": "Main landing page"}}\n'
            f'  ],\n'
            f'  "features": ["Feature 1", "Feature 2"]\n'
            f"}}"
        )

        try:
            res = coding_adapter.generate(
                prompt=prompt,
                system_prompt="You are an expert web design director. Return only valid JSON for the requested design plan.",
                language="json",
            )
            raw_text = res.get("code") or ""
            # Strip markdown codeblocks if wrapped
            clean_json = re.sub(r'^```(?:json)?\s*', '', raw_text.strip(), flags=re.MULTILINE)
            clean_json = re.sub(r'\s*```$', '', clean_json.strip(), flags=re.MULTILINE)

            data = json.loads(clean_json)
            if isinstance(data, dict) and "color_palette" in data and "hero" in data:
                return AIDesignPlan(
                    title=data.get("title", title),
                    purpose=data.get("purpose", description),
                    target_audience=data.get("target_audience", "General audience"),
                    visual_direction=data.get("visual_direction", "Modern responsive"),
                    color_palette=data.get("color_palette", {}),
                    typography=data.get("typography", {"display": "'Inter', sans-serif", "body": "'Inter', sans-serif"}),
                    hero=data.get("hero", {}),
                    sections=data.get("sections", []),
                    form_spec=data.get("form_spec"),
                    pages=data.get("pages", [{"filename": "index.html", "title": "Home", "purpose": "Overview"}]),
                    features=data.get("features", []),
                    ai_provider=res.get("provider", "ai_brain"),
                    is_fallback=False,
                )
        except Exception:
            pass

        return None

    @classmethod
    def _create_dynamic_neutral_plan(
        cls,
        title: str,
        description: str,
        theme: Optional[str],
        requested_pages: List[str],
    ) -> AIDesignPlan:
        """
        Creates a clean, neutral fallback plan derived directly from the user's prompt words.
        Contains ZERO hardcoded domain dictionaries (no sports lists, no food lists, no SaaS copy).
        """
        # Extract potential custom color cues if explicitly stated (e.g. 'blue', 'green', 'dark')
        theme_str = f"{theme or ''} {description}".lower()
        if "blue" in theme_str:
            primary = "#2563eb"
            primary_hover = "#1d4ed8"
        elif "green" in theme_str:
            primary = "#16a34a"
            primary_hover = "#15803d"
        elif "purple" in theme_str or "violet" in theme_str:
            primary = "#7c3aed"
            primary_hover = "#6d28d9"
        elif "orange" in theme_str or "amber" in theme_str:
            primary = "#ea580c"
            primary_hover = "#c2410c"
        else:
            primary = "#0284c7"
            primary_hover = "#0369a1"

        # Build dynamic hero and sections directly from the user's prompt text
        clean_desc = description.strip() or f"Official platform for {title}"

        # Dynamically build pages list (multi-page website defaults to index, about, services, contact)
        effective_pages = requested_pages if (requested_pages and len(requested_pages) > 1) else ["index.html", "about.html", "services.html", "contact.html"]
        page_entries = []
        for p in effective_pages:
            stem = p.replace(".html", "").replace("_", " ").title()
            page_entries.append({"filename": p, "title": stem, "purpose": f"{stem} section and details"})

        # Build neutral, semantic form
        form_spec = {
            "id": "action-form",
            "heading": f"Connect with {title}",
            "lead": "Submit your details or registration request online.",
            "submit_label": "Submit Request",
            "fields": [
                {"name": "fullname", "label": "Full Name", "type": "text", "placeholder": "Jane Doe", "required": True},
                {"name": "email", "label": "Email Address", "type": "email", "placeholder": "jane@example.com", "required": True},
                {"name": "notes", "label": "Inquiry Details or Requirements", "type": "textarea", "placeholder": "Specify any details or questions...", "required": False},
            ],
        }

        # Build neutral feature cards based on the prompt
        sections = [
            {
                "id": "overview",
                "type": "cards",
                "heading": "Overview & Core Focus",
                "lead": f"Key information and specifications for {title}.",
                "cards": [
                    {
                        "title": "Project Scope",
                        "description": clean_desc,
                        "badge": "Specification",
                    },
                    {
                        "title": "Responsive Architecture",
                        "description": "Engineered with semantic HTML5, accessible CSS variables, and light/dark theme switching.",
                        "badge": "Architecture",
                    },
                    {
                        "title": "Interactive Capabilities",
                        "description": "Client-side validation, persistent theme preferences, and adaptive mobile navigation.",
                        "badge": "Interactive",
                    },
                ],
            }
        ]

        return AIDesignPlan(
            title=title,
            purpose=clean_desc,
            target_audience="Intended platform users and visitors",
            visual_direction=f"Modern, responsive layout ({theme or 'clean contrast'})",
            color_palette={
                "primary": primary,
                "primary_hover": primary_hover,
                "secondary": "#64748b",
                "accent": "#0ea5e9",
                "bg_dark": "#0f172a",
                "bg_card_dark": "#1e293b",
                "text_dark": "#f8fafc",
                "bg_light": "#f8fafc",
                "bg_card_light": "#ffffff",
                "text_light": "#0f172a",
            },
            typography={
                "display": "'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif",
                "body": "'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif",
            },
            hero={
                "badge": "OFFICIAL PLATFORM",
                "heading": title,
                "subtitle": clean_desc,
                "cta_primary": "Get Started",
                "cta_target": "#action-section",
                "cta_secondary": "Learn More",
                "cta_secondary_target": "#overview",
            },
            sections=sections,
            form_spec=form_spec,
            pages=page_entries,
            features=["Responsive semantic layout", "Theme persistence", "Client-side validation"],
            ai_provider="offline_generic_scaffolding",
            is_fallback=True,
        )


class GenericComponentRenderer:
    """Renders any AIDesignPlan into clean, accessible semantic HTML5, CSS3, and JS."""

    @classmethod
    def render_html(cls, plan: AIDesignPlan, active_page: str = "index.html") -> str:
        colors = plan.color_palette
        hero = plan.hero
        pages = plan.pages or [{"filename": "index.html", "title": "Home"}]

        # Nav links
        nav_items = ""
        for p in pages:
            fname = p.get("filename", "index.html")
            p_title = p.get("title", fname.replace(".html", "").title())
            active_cls = " active" if fname == active_page else ""
            nav_items += f'        <a href="{fname}" class="nav-link{active_cls}">{p_title}</a>\n'

        # Sections HTML
        sections_html = ""
        for sec in plan.sections:
            if sec.get("type") == "cards":
                cards_markup = ""
                for c in sec.get("cards", []):
                    b_markup = f'<span class="card-badge">{c["badge"]}</span>' if c.get("badge") else ""
                    cards_markup += f"""        <div class="card">
          {b_markup}
          <h3 class="card-title">{c.get("title", "")}</h3>
          <p class="card-desc">{c.get("description", "")}</p>
        </div>\n"""
                sections_html += f"""    <section class="content-section" id="{sec.get('id', 'section')}">
      <div class="container">
        <div class="section-header">
          <h2 class="section-title">{sec.get('heading', '')}</h2>
          <p class="section-lead">{sec.get('lead', '')}</p>
        </div>
        <div class="card-grid">
{cards_markup}
        </div>
      </div>
    </section>\n"""

        # Form HTML
        form_html = ""
        if plan.form_spec:
            fspec = plan.form_spec
            fields_markup = ""
            for f in fspec.get("fields", []):
                req = "required" if f.get("required") else ""
                req_sym = " *" if f.get("required") else ""
                if f.get("type") == "textarea":
                    fields_markup += f"""        <div class="form-group full-width">
          <label for="{f['name']}">{f['label']}{req_sym}</label>
          <textarea id="{f['name']}" name="{f['name']}" rows="4" placeholder="{f.get('placeholder', '')}" {req}></textarea>
          <span class="error-msg" id="{f['name']}-error"></span>
        </div>\n"""
                elif f.get("type") == "select":
                    opts = "\n".join(f'            <option value="{o}">{o}</option>' for o in f.get("options", []))
                    fields_markup += f"""        <div class="form-group">
          <label for="{f['name']}">{f['label']}{req_sym}</label>
          <select id="{f['name']}" name="{f['name']}" {req}>
{opts}
          </select>
          <span class="error-msg" id="{f['name']}-error"></span>
        </div>\n"""
                else:
                    fields_markup += f"""        <div class="form-group">
          <label for="{f['name']}">{f['label']}{req_sym}</label>
          <input type="{f.get('type', 'text')}" id="{f['name']}" name="{f['name']}" placeholder="{f.get('placeholder', '')}" {req}>
          <span class="error-msg" id="{f['name']}-error"></span>
        </div>\n"""

            form_html = f"""    <section class="action-section" id="action-section">
      <div class="container form-container">
        <div class="section-header text-center">
          <h2 class="section-title">{fspec.get('heading', 'Get in Touch')}</h2>
          <p class="section-lead">{fspec.get('lead', '')}</p>
        </div>
        <form id="action-form" class="styled-form" novalidate>
          <div class="form-grid">
{fields_markup}
          </div>
          <button type="submit" class="btn btn-primary btn-block">{fspec.get('submit_label', 'Submit')}</button>
          <div id="form-feedback" class="form-feedback hidden"></div>
        </form>
      </div>
    </section>\n"""

        return f"""<!DOCTYPE html>
<html lang="en" data-theme="dark">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{plan.title} — {plan.purpose}</title>
  <link rel="stylesheet" href="style.css">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800&display=swap" rel="stylesheet">
</head>
<body>
  <header class="site-header">
    <div class="container nav-container">
      <a href="index.html" class="logo">⚡ {plan.title}</a>
      <button class="menu-toggle" id="menu-btn" aria-label="Toggle Navigation">☰</button>
      <nav class="nav-links" id="nav-links">
{nav_items}
        <button id="theme-toggle" class="theme-btn" title="Toggle Light/Dark Theme">🌙</button>
      </nav>
    </div>
  </header>

  <main>
    <section class="hero-section">
      <div class="container hero-content">
        <span class="badge">{hero.get('badge', 'OVERVIEW')}</span>
        <h1 class="hero-title">{hero.get('heading', plan.title)}</h1>
        <p class="hero-subtitle">{hero.get('subtitle', plan.purpose)}</p>
        <div class="hero-cta">
          <a href="{hero.get('cta_target', '#action-section')}" class="btn btn-primary">{hero.get('cta_primary', 'Get Started')}</a>
          <a href="{hero.get('cta_secondary_target', '#overview')}" class="btn btn-outline">{hero.get('cta_secondary', 'Learn More')}</a>
        </div>
      </div>
    </section>

{sections_html}
{form_html}
  </main>

  <footer class="site-footer">
    <div class="container footer-content">
      <div class="footer-brand">
        <h3>⚡ {plan.title}</h3>
        <p>{plan.purpose}</p>
      </div>
      <div class="footer-bottom">
        <p>&copy; 2026 {plan.title}. Built with MIND Universal Studio.</p>
      </div>
    </div>
  </footer>

  <script src="js/main.js"></script>
</body>
</html>
"""

