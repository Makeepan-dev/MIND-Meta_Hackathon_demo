    def verify(self, project_path: Path) -> ExecutionReport:
        errors: List[str] = []
        details: Dict[str, Any] = {"files_checked": []}

        # Check required files
        for req in ["index.html", "style.css", "js/main.js", "app/main.py", "tests/test_custom.py", "project.json"]:
            p = project_path / req
            if not p.exists() or p.stat().st_size == 0:
                errors.append(f"Missing or empty required custom file: {req}")
            else:
                details["files_checked"].append(req)

        # Run pytest on tests/test_custom.py
        test_file = project_path / "tests" / "test_custom.py"
        if test_file.exists():
            try:
                res = subprocess.run(
                    [sys.executable, "-m", "pytest", str(test_file), "-q"],
                    cwd=str(project_path),
                    capture_output=True,
                    text=True,
                    timeout=15,
                )
                details["pytest_returncode"] = res.returncode
                if res.returncode != 0:
                    errors.append(f"Custom pytest suite failed: {res.stdout.strip()}")
            except Exception as e:
                errors.append(f"Could not execute pytest: {e}")

        success = len(errors) == 0
        summary = "Custom project verified successfully with dual Web/CLI entrypoints and passing pytest suite." if success else f"Custom project verification failed with {len(errors)} issues."

        import uuid
        return ExecutionReport(
            workflow_id=f"custom_{uuid.uuid4().hex[:6]}",
            project_name=project_path.name,
            project_type=self.project_type.value,
            success=success,
            status="VERIFIED" if success else "FAILED",
            errors=errors,
            summary=summary,
            entry_point="index.html",
            details=details,
        )

