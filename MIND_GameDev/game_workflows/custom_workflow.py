        self._write_readme(workspace, title, desc)
        self._write_manifest(workspace, title, desc)

        return {
            "status": "SUCCESS",
            "project_type": "custom",
            "title": title,
            "entry_point": "index.html",
            "cli_entry": "app/main.py",
        }

