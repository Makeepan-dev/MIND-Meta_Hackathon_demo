"""
MIND_GameDev — Endless Runner Game Generator.
Generates a complete, verified, playable 3D endless runner game in Three.js (WebGL).
Includes 3-lane movement, jumping, sliding, obstacles, collectibles, procedural track recycling,
Web Audio API sound synthesis, HUD, and 3D glTF asset loading with procedural fallbacks.
"""

import shutil
from pathlib import Path
from typing import Dict, Any, Optional

from ..tools.workspace_files import SafeWorkspaceManager
from ..models import GameSpecification


class EndlessRunnerGenerator:
    """Generates the code and structure for a standalone 3D endless runner game."""

    def __init__(self, workspace: SafeWorkspaceManager) -> None:
        self.workspace = workspace

    def build_project(self, spec: Optional[GameSpecification] = None) -> Dict[str, Any]:
        """Creates all game files, styles, scripts, and libraries in the project workspace."""
        title = spec.title if spec else "CyberDash 3D: Endless Runner"
        theme = spec.theme if spec else "cyberpunk neon arcade"

        # 1. Copy bundled three.module.min.js into libs/
        self._bundle_libraries()

        # 2. Write index.html
        self._write_index_html(title)

        # 3. Write style.css
        self._write_styles()

        # 4. Write modular JavaScript files
        self._write_audio_js()
        self._write_player_js()
        self._write_track_js()
        self._write_obstacles_js()
        self._write_collectibles_js()
        self._write_main_game_js(title, theme)

        # 5. Write project metadata
        self._write_project_manifest(title, theme)

        return {
            "status": "SUCCESS",
            "game_title": title,
            "project_dir": str(self.workspace.base_directory),
            "entry_point": "index.html",
        }

    def _bundle_libraries(self) -> None:
        """Copies pinned three.module.min.js into project libs directory."""
        self.workspace.create_directory("libs")
        source_lib = Path(__file__).resolve().parent.parent / "libs" / "three.module.min.js"
        dest_lib = self.workspace.base_directory / "libs" / "three.module.min.js"

        if source_lib.exists():
            shutil.copy2(source_lib, dest_lib)
        else:
            # Fallback stub if missing
            self.workspace.write_file(
                "libs/three.module.min.js",
                "// Three.js module placeholder\nconsole.warn('Three.js library missing');",
            )

